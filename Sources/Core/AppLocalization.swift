import Foundation

struct L10n {
    static func text(_ key: String, _ language: AppSettingsStore.Language) -> String {
        let code = language.rawValue
        return dictionary[code]?[key] ?? dictionary["en"]?[key] ?? key
    }

    static func format(_ key: String, _ language: AppSettingsStore.Language, _ arguments: CVarArg...) -> String {
        String(
            format: text(key, language),
            locale: Locale(identifier: language.localeIdentifier),
            arguments: arguments
        )
    }

    static func city(_ raw: String, _ language: AppSettingsStore.Language) -> String {
        switch raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() {
        case "makkah", "mecca": return text("city_makkah", language)
        case "madinah", "medina": return text("city_madinah", language)
        default: return raw
        }
    }

    static func date(_ raw: String, _ language: AppSettingsStore.Language) -> String {
        let input = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !input.isEmpty else { return raw }

        let source = DateFormatter()
        source.locale = Locale(identifier: "en_US_POSIX")
        source.calendar = Calendar(identifier: .gregorian)
        source.timeZone = TimeZone(secondsFromGMT: 0)
        source.dateFormat = "yyyy-MM-dd"
        guard let parsed = source.date(from: String(input.prefix(10))) else { return raw }

        let output = DateFormatter()
        output.locale = Locale(identifier: language.localeIdentifier)
        output.calendar = Calendar(identifier: .gregorian)
        output.timeZone = TimeZone(secondsFromGMT: 0)
        output.dateStyle = .medium
        output.timeStyle = .none
        return output.string(from: parsed)
    }

    static func status(_ raw: String, _ language: AppSettingsStore.Language) -> String {
        let normalized = raw.uppercased()
        switch normalized {
        case "NEW", "AVAILABILITY_CHECK": return text("status_availability", language)
        case "PAYMENT_PENDING": return text("status_payment", language)
        case "PAID", "BOOKING_CONFIRMED": return text("status_confirmed", language)
        case "DOCUMENTS_READY", "READY_TO_TRAVEL": return text("status_ready", language)
        case "IN_TRIP": return text("status_in_trip", language)
        case "COMPLETED": return text("status_completed", language)
        case "CANCELLED": return text("status_cancelled", language)
        default: return raw.replacingOccurrences(of: "_", with: " ").capitalized
        }
    }

    static func error(_ error: Error, _ language: AppSettingsStore.Language) -> String {
        if let bookingError = error as? BookingStoreError {
            switch bookingError {
            case .permanentDeleteUnavailable:
                return text("booking_delete_server_required", language)
            case .authoritativeQuoteRequired:
                return text("booking_authoritative_quote_required", language)
            }
        }
        if let flightError = error as? FlightEngineAvailabilityError {
            switch flightError {
            case .flightProviderNotConfigured:
                return text("flight_provider_not_configured", language)
            case .realOutboundRequired:
                return text("flight_error_outbound", language)
            case .noVerifiedFlights:
                return text("flight_search_failed", language)
            }
        }
        if let providerError = error as? IgnavFlightProviderError {
            switch providerError {
            case .invalidRequest:
                return text("flight_search_failed", language)
            case .serverUnavailable:
                return text("error_network", language)
            case .searchFailed:
                return text("flight_search_failed", language)
            }
        }
        if let urlError = error as? URLError {
            switch urlError.code {
            case .notConnectedToInternet, .networkConnectionLost:
                return text("error_offline", language)
            case .timedOut:
                return text("error_timeout", language)
            default:
                return text("error_network", language)
            }
        }
        guard let apiError = error as? APIError else { return text("error_unknown", language) }
        switch apiError {
        case .invalidResponse:
            return text("error_invalid_response", language)
        case .status(let code):
            return format("error_status", language, code)
        case .server(_, let message):
            let normalized = message.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()
            let localized: String
            switch normalized {
            case "CHAT_NOT_FOUND", "BOOKING_NOT_FOUND":
                localized = text("error_booking_access", language)
            case "RATE_LIMIT":
                localized = text("error_rate_limit", language)
            case "CHAT_READ_FAILED":
                localized = text("error_chat_load", language)
            case "CHAT_SEND_FAILED":
                localized = text("error_chat_send", language)
            case "CHAT_DB_NOT_CONFIGURED", "BOOKING_DB_NOT_CONFIGURED", "HOTELS_DB_NOT_CONFIGURED":
                localized = text("error_service_unavailable", language)
            case "HOTEL_NOT_FOUND", "HOTEL_CITY_MISMATCH":
                localized = text("hotel_not_available", language)
            case "ROOM_NOT_FOUND", "ROOM_CATEGORY_NOT_FOUND":
                localized = text("room_not_available", language)
            case "BOOKING_UPDATE_FAILED":
                localized = text("booking_update_failed", language)
            case "BOOKING_DELETE_FAILED":
                localized = text("booking_delete_failed", language)
            case "INVALID_REQUEST", "EMPTY_MESSAGE", "INVALID_BOOKING", "INVALID_HOTEL":
                localized = text("error_invalid_request", language)
            default:
                localized = format("error_server_named", language, message)
            }
            return normalized.isEmpty ? localized : "\(localized) [\(normalized)]"
        case .decoding:
            return text("error_decoding", language)
        case .missingBookingToken:
            return text("error_missing_booking_token", language)
        }
    }

